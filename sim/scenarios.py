"""60 daily hunts under five kinds of community behaviour, using the reference model.

    python3 sim/scenarios.py      # writes docs/sim.svg and sim/scenarios.md

Parameters are the proposed mainnet ones (daily hunts). They differ from the testnet
deployment only in round length and the 1% target floor used there so that a judge
plus two helper accounts can finish a hunt; see README.
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from staghunt_sim import Config, Model  # noqa: E402

DAY = 86_400
DAYS = 60
STAG = 10**18
HOLDERS = 100

CFG = Config(
    round_secs=DAY,
    reward_bps=1000,
    burn_bps=500,
    start_target_bps=2000,
    target_step_up_bps=500,
    target_step_down_bps=500,
    min_target_bps=500,
    max_target_bps=6000,
    min_hunters=3,
    faucet_amount=0,
    faucet_closes_at_s=0,
)


class Lcg:
    def __init__(self, seed: int) -> None:
        self.s = seed

    def next(self) -> int:
        self.s = (self.s * 6364136223846793005 + 1442695040888963407) % 2**64
        return self.s >> 33

    def chance(self, p: float) -> bool:
        return (self.next() % 10_000) < p * 10_000


def run(name: str, policy, seed: int = 7, whale_share: float = 0.0):
    m = Model(CFG)
    names = [f"h{i}" for i in range(HOLDERS)]
    total = HOLDERS * 1000 * STAG
    if whale_share:
        m.balances["whale"] = int(total * whale_share)
        rest = (total - m.balances["whale"]) // HOLDERS
        for n in names:
            m.balances[n] = rest
    else:
        for n in names:
            m.balances[n] = 1000 * STAG
    rng = Lcg(seed)
    supply = [m.supply()]
    last_won = None
    for day in range(DAYS):
        m.advance(60)  # a minute into the day
        for who in list(m.balances):
            frac = policy(who, day, rng, last_won)
            if frac and m.balances[who] > 0:
                m.join(who, max(1, m.balances[who] * int(frac * 100) // 100))
        m.advance(DAY - 60)
        last = m.history[-1] if m.history and m.history[-1]["round"] == day else None
        last_won = bool(last and last["won"])
        supply.append(m.supply())
    return {
        "name": name,
        "supply": supply,
        "won": m.won,
        "lost": m.lost,
        "empty": m.empty,
        "final_target_bps": m.target_bps,
        "change": supply[-1] / supply[0] - 1,
        "best_streak": m.best_streak,
    }


SCENARIOS = [
    ("Coordinated herd: 70% join daily with half their STAG",
     lambda who, d, r, lw: 0.5 if r.chance(0.70) else 0),
    ("Apathy: 8% join daily",
     lambda who, d, r, lw: 0.3 if r.chance(0.08) else 0),
    ("Fair-weather: 60% join after a win, 15% after a loss",
     lambda who, d, r, lw: 0.5 if r.chance(0.60 if lw in (None, True) else 0.15) else 0),
    ("Random mood: 0-60% join, changes every day",
     None),  # filled below
]


def mood_policy():
    state = {"day": -1, "p": 0.0}

    def policy(who, d, r, lw):
        if state["day"] != d:
            state["day"] = d
            state["p"] = (r.next() % 61) / 100
        return 0.5 if r.chance(state["p"]) else 0

    return policy


def whale_policy(who, d, r, lw):
    if who == "whale":
        return 1.0  # all in, every day
    return 0.5 if r.chance(0.02) else 0  # a couple of friends


def main() -> None:
    results = []
    for name, pol in SCENARIOS:
        results.append(run(name, pol if pol else mood_policy()))
    results.append(run("Whale with 30% of supply + 2% of the crowd", whale_policy, whale_share=0.30))

    # ---- markdown table ----
    lines = [
        "| Scenario | Won | Lost | Supply after 60 days | Target at the end | Best streak |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for r in results:
        lines.append(
            f"| {r['name']} | {r['won']} | {r['lost']} | {r['change']:+.1%} | {r['final_target_bps'] / 100:.0f}% | {r['best_streak']} |"
        )
    table = "\n".join(lines)
    (HERE / "scenarios.md").write_text(
        "# 60 daily hunts, five behaviours\n\nGenerated by `python3 sim/scenarios.py` with the reference model "
        "(`sim/staghunt_sim.py`), 100 holders starting with 1,000 STAG each, mainnet parameters "
        "(+10% / -5%, target 20% start, +/-5 points, 5%-60%, 3 hunters minimum).\n\n" + table + "\n\n![supply](../docs/sim.svg)\n"
    )
    print(table)

    # ---- svg chart ----
    w, h, pad_l, pad_r, pad_t, pad_b = 760, 360, 56, 16, 16, 120
    all_vals = [v / r["supply"][0] for r in results for v in r["supply"]]
    lo, hi = min(all_vals), max(all_vals)
    lo, hi = lo - 0.02, hi + 0.02
    colors = ["#2f7d4f", "#a2412c", "#c08a1e", "#3b6fb6", "#7a4fb0"]

    def xy(i, v):
        x = pad_l + i * (w - pad_l - pad_r) / DAYS
        y = pad_t + (hi - v) * (h - pad_t - pad_b) / (hi - lo)
        return f"{x:.1f},{y:.1f}"

    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" font-family="system-ui,sans-serif" font-size="12">',
        f'<rect width="{w}" height="{h}" fill="#ffffff"/>',
    ]
    for t in [x / 10 for x in range(int(lo * 10), int(hi * 10) + 2)]:
        if lo <= t <= hi:
            y = pad_t + (hi - t) * (h - pad_t - pad_b) / (hi - lo)
            parts.append(f'<line x1="{pad_l}" x2="{w - pad_r}" y1="{y:.1f}" y2="{y:.1f}" stroke="#e5e5e5"/>')
            parts.append(f'<text x="{pad_l - 6}" y="{y + 4:.1f}" text-anchor="end" fill="#666">{t:.1f}×</text>')
    for d in range(0, DAYS + 1, 10):
        x = pad_l + d * (w - pad_l - pad_r) / DAYS
        parts.append(f'<text x="{x:.1f}" y="{h - pad_b + 16}" text-anchor="middle" fill="#666">day {d}</text>')
    for r, c in zip(results, colors):
        pts = " ".join(xy(i, v / r["supply"][0]) for i, v in enumerate(r["supply"]))
        parts.append(f'<polyline fill="none" stroke="{c}" stroke-width="2" points="{pts}"/>')
    for k, (r, c) in enumerate(zip(results, colors)):
        y = h - pad_b + 36 + k * 16
        parts.append(f'<rect x="{pad_l}" y="{y - 9}" width="12" height="4" fill="{c}"/>')
        parts.append(f'<text x="{pad_l + 18}" y="{y - 4}" fill="#222">{r["name"]} ({r["change"]:+.0%})</text>')
    parts.append(f'<text x="{pad_l}" y="{pad_t - 4}" fill="#666">STAG supply relative to day 0</text>')
    parts.append("</svg>")
    (HERE.parent / "docs" / "sim.svg").write_text("\n".join(parts) + "\n")
    print("wrote docs/sim.svg and sim/scenarios.md")


if __name__ == "__main__":
    main()
